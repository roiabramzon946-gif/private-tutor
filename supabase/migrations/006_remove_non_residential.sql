-- מורה שבחר אחד מהם (לא סביר) — העיר שלו מתאפסת
update public.teachers t set city = null, region = null
  from public.localities l
 where l.name = t.city
   and l.code in (1411, 1414, 1418, 1412, 1415, 1196, 1413, 1416,   -- מחנות צבא
                  2039, 1094, 1056, 1084, 890, 1195);               -- מוסדות

delete from public.localities
 where code in (1411, 1414, 1418, 1412, 1415, 1196, 1413, 1416,
                2039, 1094, 1056, 1084, 890, 1195);
